// KV cache: none
// `rlmh setup` and the first-run check (step 10, decision 10a): find or fetch Python 3.12 through uv
// into <home>/python/, copy the engine out of this binary into <home>/engine/<APP_VERSION>/, write
// .installed.json last, then start the installed engine once to check it.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { dirname, join, resolve, sep } from "node:path";
import {
  EngineNotFound,
  engineEnv,
  fetchInfo,
  findEngine,
  installedEngine,
  readInstalled,
  startEngine,
  stripKeys,
  type EngineCommand,
  type Installed,
} from "../engine.ts";
import { binDir, engineDir, pythonDir } from "../paths.ts";
import { APP_VERSION } from "../version.ts";

export interface EngineBundle {
  files: { path: string; sha256: string; file: string }[];
  sha256: string;
}

/** Runs argv with env; returns the exit code and stdout. stderr goes to the user's terminal (uv's progress) unless quiet. */
export type UvRunner = (argv: string[], env: Record<string, string>, opts?: { quiet?: boolean }) => Promise<{ code: number; stdout: string }>;

export type EngineCheck = (cmd: EngineCommand) => Promise<{ ok: true } | { ok: false; message: string; stderr: string[] }>;

export interface SetupOptions {
  home: string;
  yes: boolean;
  force?: boolean;
  interactive: boolean;
  env?: Record<string, string | undefined>;
  out?: (line: string) => void;
  ask?: (q: string) => Promise<boolean>;
  runUv?: UvRunner;
  bundle?: EngineBundle | null;
  platform?: NodeJS.Platform;
  /** Runs the found Python for its version and shell; tests replace it. */
  runPython?: UvRunner;
  /** Starts the installed engine and asks engine.info; tests replace it. */
  checkEngine?: EngineCheck;
  /** Replaces import.meta.dir in ensureEngine's findEngine call, for tests (as in findEngine). */
  sourceDir?: string;
}

const CHECK_TIMEOUT_MS = 60_000;
const EXIT_WAIT_MS = 3_000;
const LONG_HOME = 60;

const NO_UV = (home: string) =>
  `uv was not found in ${binDir(home)} or on PATH. Re-run the install script, or install uv (https://docs.astral.sh/uv/) and run "rlmh setup".`;
const DECLINED = `Not installed. Run "rlmh setup" when you are ready, or set RLMH_ENGINE to your own engine command.`;
const NO_TTY = `rlmh needs Python 3.12 for its engine and has none yet. Run "rlmh setup --yes" to download it through uv, or set RLMH_ENGINE to your own engine command.`;
const DOWNLOAD_FAILED = (code: number) =>
  `Could not download Python 3.12 (uv exited ${code}). Check your network or proxy (uv honours HTTPS_PROXY), or set UV_PYTHON_INSTALL_MIRROR. Nothing was recorded; run "rlmh setup" again when online.`;
const QUESTION = (home: string) =>
  `rlmh needs Python 3.12 for its engine and has none yet. Download it now (standalone build, through uv, tens of MB) into ${pythonDir(home)}${sep} and copy the engine to ${engineDir(APP_VERSION, home)}${sep}? Nothing else on this machine changes. [Y/n] `;

/** Prints the Python version, then find_shell()'s name (empty when it fails); argv[1] is the engine folder. */
const PROBE = [
  "import platform, sys",
  "print(platform.python_version())",
  "try:",
  "    sys.path.insert(0, sys.argv[1])",
  "    from rlm_engine.workspace import find_shell",
  "    print(find_shell().name)",
  "except Exception:",
  "    print('')",
].join("\n");

/** The engine files this binary carries, or null for a build without them (a source run). */
export async function loadBundle(): Promise<EngineBundle | null> {
  try {
    // @ts-ignore: generated by scripts/embed-engine.ts and git-ignored, so absent in a fresh checkout
    const m = await import("../../build/engine-files.ts");
    return { files: m.ENGINE_FILES, sha256: m.ENGINE_BUNDLE_SHA256 };
  } catch {
    return null;
  }
}

/** <home>/bin/uv[.exe], then PATH. */
export function findUv(opts: { home: string; env?: Record<string, string | undefined> }): string | null {
  const own = join(binDir(opts.home), process.platform === "win32" ? "uv.exe" : "uv");
  if (existsSync(own)) return own;
  return Bun.which("uv", { PATH: pathOf(opts.env ?? process.env) }) ?? null;
}

/** Writes every file byte-exact into <dest>.tmp, then swaps it in for <dest>. */
export function extractEngine(bundle: EngineBundle, dest: string): void {
  const tmp = `${dest}.tmp`;
  rmSync(tmp, { recursive: true, force: true });
  mkdirSync(tmp, { recursive: true });
  for (const f of bundle.files) {
    const bytes = readFileSync(f.file);
    if (sha256(bytes) !== f.sha256) throw new Error(`the embedded ${f.path} does not match its manifest`);
    const target = join(tmp, f.path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, bytes);
  }
  rmSync(dest, { recursive: true, force: true });
  renameSync(tmp, dest);
}

/** `rlmh setup [--yes] [--force]`; returns the exit code. */
export async function runSetup(o: SetupOptions): Promise<number> {
  return install(o, false);
}

/**
 * Called before info, run, batch and the interactive app. Returns when an engine is found or was just
 * installed; otherwise throws EngineNotFound (`reported` when setup already printed why).
 */
export async function ensureEngine(o: Omit<SetupOptions, "yes">): Promise<void> {
  let missing: EngineNotFound;
  try {
    findEngine({ home: o.home, env: o.env, sourceDir: o.sourceDir });
    return;
  } catch (e) {
    if (!(e instanceof EngineNotFound)) return; // a bad RLMH_ENGINE: the command reports it, as before step 10
    missing = e;
  }
  const bundle = o.bundle !== undefined ? o.bundle : await loadBundle();
  if (bundle === null) throw missing;
  const env = o.env ?? process.env;
  // an upgrade: a Python is already there, so copy this version's engine without asking
  const hasPython = (await existingPython(o.home, env, o.runUv ?? spawnRunner)) !== null;
  if (!hasPython && !o.interactive) throw new EngineNotFound(NO_TTY);
  const code = await install({ ...o, bundle, yes: hasPython }, hasPython);
  if (code !== 0) throw new EngineNotFound("setup did not finish", { reported: true });
}

async function install(o: SetupOptions, upgrade: boolean): Promise<number> {
  const env = o.env ?? process.env;
  const out = o.out ?? ((line: string) => void process.stdout.write(`${line}\n`));
  const runUv = o.runUv ?? spawnRunner;
  const runPython = o.runPython ?? spawnRunner;
  const bundle = o.bundle !== undefined ? o.bundle : await loadBundle();
  if (bundle === null) {
    out(`This rlmh runs from source and carries no engine; it uses the checkout's engine. Nothing was installed.`);
    return 1;
  }
  const home = o.home;
  if ((o.platform ?? process.platform) === "win32" && home.length > LONG_HOME) {
    out(`warning: ${home} is ${home.length} characters long, and Windows paths stop at 260 unless long paths are on. If setup or a run fails on a path, set RLMH_HOME=C:\\rlmh and run "rlmh setup" again.`);
  }
  const dest = engineDir(APP_VERSION, home);
  const marker = readInstalled(dest);
  if (!o.force && marker !== null && marker.bundle_sha256 === bundle.sha256 && installedEngine(home, {}) !== null) {
    out(`already installed: engine ${dest}, Python ${marker.python_version} (${marker.python})`);
    return 0;
  }

  let python = o.force ? null : await existingPython(home, env, runUv);
  if (python === null) {
    const uv = findUv({ home, env });
    if (uv === null) {
      out(NO_UV(home));
      return 1;
    }
    if (!o.yes) {
      if (!o.interactive) {
        out(NO_TTY);
        return 1;
      }
      if (!(await (o.ask ?? askLine)(QUESTION(home)))) {
        out(DECLINED);
        return 1;
      }
    }
    const installEnv = {
      ...stripKeys(env),
      UV_PYTHON_INSTALL_DIR: pythonDir(home),
      UV_PYTHON_BIN_DIR: join(pythonDir(home), "bin"),
      UV_PYTHON_INSTALL_BIN: "0",
      UV_PYTHON_INSTALL_REGISTRY: "0",
    };
    const installed = await runUv([uv, "python", "install", "3.12", ...(o.force ? ["--reinstall"] : [])], installEnv);
    if (installed.code !== 0) {
      out(DOWNLOAD_FAILED(installed.code));
      return 1;
    }
    const found = await uvFind(uv, home, env, runUv);
    if (found === null) {
      out(`uv installed Python 3.12, but "uv python find 3.12" did not report it.`);
      return 1;
    }
    if (!found.inside) {
      out(`"uv python find 3.12" gave ${found.path}, which is outside ${pythonDir(home)}; refusing to use it.`);
      return 1;
    }
    python = found.path;
  }

  if (upgrade) out(`Copying the engine for rlmh ${APP_VERSION} to ${dest}`);
  extractEngine(bundle, dest);
  const probe = await runPython([python, "-E", "-s", "-c", PROBE, dest], stripKeys(env), { quiet: true });
  const [version = "", shell = ""] = probe.stdout.split(/\r?\n/).map((s) => s.trim());
  if (probe.code !== 0 || version === "") {
    out(`The Python at ${python} did not run (exit ${probe.code}). Run "rlmh setup --force" to install it again.`);
    return 1;
  }
  writeInstalled(dest, {
    app_version: APP_VERSION,
    bundle_sha256: bundle.sha256,
    python,
    python_version: version,
    installed_at: new Date().toISOString(),
  });

  const cmd = installedEngine(home, engineEnv(home, env));
  const check = cmd === null ? { ok: false as const, message: "the extracted engine is incomplete", stderr: [] } : await (o.checkEngine ?? checkInstalled)(cmd);
  if (!check.ok) {
    rmSync(join(dest, ".installed.json"), { force: true });
    out(`The installed engine did not start: ${check.message}`);
    for (const line of check.stderr) out(line);
    return 1;
  }
  if (!upgrade) {
    out(`Python   ${python} (${version})`);
    out(`engine   ${dest}`);
    if (shell !== "") out(`shell() will use: ${shell}`);
  }
  return 0;
}

/** Step 2: the Python of any installed engine that still exists, else the one uv already has in <home>/python. */
async function existingPython(home: string, env: Record<string, string | undefined>, runUv: UvRunner): Promise<string | null> {
  const engines = join(home, "engine");
  const versions = existsSync(engines) ? readdirSync(engines).sort() : [];
  for (const version of versions) {
    const marker = readInstalled(join(engines, version));
    if (marker !== null && existsSync(marker.python)) return marker.python;
  }
  const uv = findUv({ home, env });
  if (uv === null) return null;
  const found = await uvFind(uv, home, env, runUv);
  return found !== null && found.inside ? found.path : null;
}

/** `uv python find 3.12` among the Pythons in <home>/python only, with downloads off. */
async function uvFind(uv: string, home: string, env: Record<string, string | undefined>, runUv: UvRunner) {
  const r = await runUv([uv, "python", "find", "3.12"], {
    ...stripKeys(env),
    UV_PYTHON_INSTALL_DIR: pythonDir(home),
    UV_MANAGED_PYTHON: "1",
    UV_PYTHON_DOWNLOADS: "never",
  }, { quiet: true }); // "No interpreter found" is an answer here, not an error
  const path = r.stdout.trim().split(/\r?\n/)[0]?.trim() ?? "";
  if (r.code !== 0 || path === "") return null;
  return { path, inside: isInside(path, pythonDir(home)) };
}

function isInside(path: string, dir: string): boolean {
  const fold = (p: string) => (process.platform === "win32" ? p.toLowerCase() : p);
  return fold(resolve(path)).startsWith(fold(resolve(dir) + sep));
}

function writeInstalled(dest: string, marker: Installed): void {
  const path = join(dest, ".installed.json");
  writeFileSync(`${path}.tmp`, `${JSON.stringify(marker, null, 2)}\n`);
  renameSync(`${path}.tmp`, path);
}

async function checkInstalled(cmd: EngineCommand): Promise<{ ok: true } | { ok: false; message: string; stderr: string[] }> {
  const engine = startEngine(cmd);
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    const timeout = new Promise<never>((_, reject) => {
      timer = setTimeout(() => reject(new Error(`no engine.info answer within ${CHECK_TIMEOUT_MS / 1000} s`)), CHECK_TIMEOUT_MS);
    });
    await Promise.race([fetchInfo(engine.link), timeout]);
    return { ok: true };
  } catch (e) {
    return { ok: false, message: e instanceof Error ? e.message : String(e), stderr: engine.stderrTail() };
  } finally {
    clearTimeout(timer);
    engine.kill();
    await Promise.race([engine.exited, Bun.sleep(EXIT_WAIT_MS)]);
  }
}

const spawnRunner: UvRunner = async (argv, env, opts = {}) => {
  try {
    const proc = Bun.spawn({ cmd: argv, env, stdin: "ignore", stdout: "pipe", stderr: opts.quiet ? "ignore" : "inherit" });
    const stdout = await new Response(proc.stdout).text();
    return { code: await proc.exited, stdout };
  } catch {
    return { code: 127, stdout: "" }; // could not start it at all
  }
};

/** One line from the terminal: Enter or y means yes. The question goes to stderr, so --json stdout stays clean. */
async function askLine(question: string): Promise<boolean> {
  const rl = createInterface({ input: process.stdin, output: process.stderr });
  try {
    const answer = await new Promise<string | null>((done) => {
      rl.once("close", () => done(null)); // Ctrl-D: no
      rl.question(question, done);
    });
    return answer !== null && /^\s*(y|yes)?\s*$/i.test(answer);
  } finally {
    rl.close();
  }
}

function pathOf(env: Record<string, string | undefined>): string {
  // Windows names it Path, and a copied env object is case-sensitive
  const name = Object.keys(env).find((k) => k.toUpperCase() === "PATH");
  return (name && env[name]) || "";
}

function sha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}
