// KV cache: none
// Writes build/engine-files.ts: one `import … with { type: "file" }` per file under engine/rlm_engine/
// (step 10). A compiled rlmh carries those files and `rlmh setup` copies them out byte for byte.
// Run from app/: `bun run scripts/embed-engine.ts`.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const APP = resolve(import.meta.dir, "..");
const ENGINE = resolve(APP, "..", "engine");
const PACKAGE = join(ENGINE, "rlm_engine");
const OUT = join(APP, "build", "engine-files.ts");

/** Every file under `dir`, as `/`-paths relative to `base`, without __pycache__ or .pyc. */
function walk(dir: string, base: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "__pycache__" || entry.name.endsWith(".pyc")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, base));
    else if (entry.isFile()) out.push(relative(base, full).split("\\").join("/"));
  }
  return out;
}

const sha256 = (bytes: Uint8Array | string) => createHash("sha256").update(bytes).digest("hex");

const paths = walk(PACKAGE, ENGINE).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
if (!paths.includes("rlm_engine/__main__.py")) {
  console.error(`embed-engine: ${join(PACKAGE, "__main__.py")} is missing`);
  process.exit(1);
}

const files = paths.map((path) => ({ path, sha256: sha256(readFileSync(join(ENGINE, path))) }));
const bundleSha = sha256(files.map((f) => `${f.path}\0${f.sha256}\n`).join(""));

const lines = [
  "// KV cache: none",
  "// Generated by app/scripts/embed-engine.ts; do not edit. In a compiled binary each import is a path",
  "// in the embedded filesystem; from source it is the real file.",
  "// @ts-nocheck",
  "",
  ...files.map((f, i) => `import f${i} from ${JSON.stringify(`../../engine/${f.path}`)} with { type: "file" };`),
  "",
  "export const ENGINE_FILES: { path: string; sha256: string; file: string }[] = [",
  ...files.map((f, i) => `  { path: ${JSON.stringify(f.path)}, sha256: ${JSON.stringify(f.sha256)}, file: f${i} },`),
  "];",
  "",
  `export const ENGINE_BUNDLE_SHA256 = ${JSON.stringify(bundleSha)};`,
  "",
];

mkdirSync(join(APP, "build"), { recursive: true });
const text = lines.join("\n");
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) writeFileSync(OUT, text);
console.log(`embed-engine: ${files.length} files, bundle ${bundleSha.slice(0, 12)}…, wrote ${relative(APP, OUT)}`);
